import { createHash } from 'crypto';
import { promises as fs } from 'fs';
import path from 'path';
import { isPublishable, PUBLISHABLE_MAINS } from '../constants';
import { CvPathError, REPO_ROOT } from './paths';
import { compileCv } from './tectonic';

/**
 * Publish = compile, then replace the site's resume PDF and regenerate features/Resume/resumePdf.ts, whose
 * hash busts the one-week /assets cache. The /cv editor's Publish button and `npm run cv:build` both run this.
 */

const PUBLIC_PDF_PATH = '/assets/resume/Daffa_Aditya_Rahman_CV.pdf';
const PDF_FILE = path.join(REPO_ROOT, 'public', ...PUBLIC_PDF_PATH.split('/').filter(Boolean));
const MODULE_FILE = path.join(REPO_ROOT, 'features', 'Resume', 'resumePdf.ts');

/** `changed` is false when both files already held this build, so nothing was written. */
export type PublishResult = { ok: true; path: string; hash: string; changed: boolean } | { ok: false; error: string; log: string };

function resumePdfModule(hash: string, main: string): string {
  return `// Generated by the /cv editor's Publish button (or \`npm run cv:build\`). Do not edit by hand.
// Built from cv-src/${main}.
// The hash busts the one-week cache on /assets when the PDF changes.
export const RESUME_PDF = {
  path: '${PUBLIC_PDF_PATH}',
  hash: '${hash}',
} as const;
`;
}

/** `main` must already be validated (see assertMain). */
export async function publishCv(main: string): Promise<PublishResult> {
  if (!isPublishable(main)) throw new CvPathError(`Only ${PUBLISHABLE_MAINS.join(', ')} can be published as the resume`);
  const result = await compileCv(main);
  if (!result.ok) return result;
  const hash = createHash('sha256').update(result.pdf).digest('hex').slice(0, 10);
  const moduleSource = resumePdfModule(hash, main);
  // Skip unchanged files so a no-op publish does not touch the dev server's watcher or git.
  const [currentPdf, currentModule] = await Promise.all([
    fs.readFile(PDF_FILE).catch(() => null),
    fs.readFile(MODULE_FILE, 'utf8').catch(() => null),
  ]);
  const pdfChanged = !currentPdf?.equals(result.pdf);
  const moduleChanged = currentModule !== moduleSource;
  if (pdfChanged) {
    await fs.mkdir(path.dirname(PDF_FILE), { recursive: true });
    await writeAtomic(PDF_FILE, result.pdf);
  }
  if (moduleChanged) await writeAtomic(MODULE_FILE, moduleSource);
  return { ok: true, path: PUBLIC_PDF_PATH, hash, changed: pdfChanged || moduleChanged };
}

/** Write then rename, so the dev server's watcher never picks up a half-written file. */
async function writeAtomic(file: string, data: string | Buffer): Promise<void> {
  const tmp = `${file}.${process.pid}.tmp`;
  await fs.writeFile(tmp, data);
  await fs.rename(tmp, file);
}
